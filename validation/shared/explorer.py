"""Helpers of citadel-explorer.ipynb: test a published LLM backend, model, alias or access contract by name.

Everything is discovered from the deployed gateway, nothing is configured by hand:
- the backend contract (policy fragment `backend-contract`, generated by modules/llm-routing on every
  llm-backend-onboarding apply): the backends, their type, their models and the model aliases;
- the APIM products (one per access contract service), their APIs, policies and subscriptions;
- environments/<env>/access-contracts/*.tfvars, when python-hcl2 is installed, to accept a contract by file
  name and to read its key from the contract's Key Vault secret.

The request is built from the model kind (chat, embeddings, image) and the backend type, on every LLM API
surface the key may call:

  backend type                                         chat                                   embeddings / images
  ai-foundry, azure-openai                             universal, azure-openai, unified /v1   embeddings: same APIs
  external, aws-bedrock-mantle, gemini-openai          universal, unified /v1                 embeddings: external
  aws-bedrock / gemini / anthropic                     unified /bedrock, /gemini, /claude
  azure-flux, azure-mai (+ image models on Foundry)                                           unified /v1/images

Keys stay in memory: they are never printed or returned.
"""
from __future__ import annotations

import html
import json
import re
import time
import urllib.parse
from dataclasses import dataclass, field, replace

import acceptance as A

OPENAI_COMPAT = {"ai-foundry", "azure-openai", "aws-bedrock-mantle", "gemini-openai", "external"}
AOAI_TYPES = {"ai-foundry", "azure-openai"}
EMBEDDING_TYPES = {"ai-foundry", "azure-openai", "external"}
IMAGE_TYPES = {"ai-foundry", "azure-openai", "azure-flux", "azure-mai"}
LLM_APIS = ("universal-llm-api", "azure-openai-api", "unified-ai-api")
AOAI_API_VERSION = "2024-10-21"
DEFAULT_PROMPT = "Reply with one short sentence: which model are you?"
ALL_ACCESS = "master"  # APIM's built-in all-access subscription

OK, FAIL, SKIP, INFO = "✅", "❌", "⏭️", "ℹ️"


def model_kind(name, types=()):
    """chat | embeddings | image | unsupported (realtime, audio, video: not callable with a simple POST)."""
    n = name.lower()
    if set(types) & {"azure-flux", "azure-mai"} or re.search(r"gpt-image|dall-e|flux|mai-image", n):
        return "image"
    if "embed" in n:
        return "embeddings"
    if re.search(r"realtime|audio|tts|whisper|transcribe|sora|speech", n):
        return "unsupported"
    return "chat"


def norm(text):
    return re.sub(r"[^a-z0-9]", "", (text or "").lower())


@dataclass
class Step:
    """One gateway call (or a reason why there is none: url is None)."""
    model: str
    kind: str
    backend_type: str = ""
    api: str = ""
    surface: str = ""
    method: str = "POST"
    url: str | None = None
    body: dict | None = None
    parser: str = "openai-chat"
    product: str = ""
    expect: tuple = (200,)
    check: str = "call"           # call | denied-model | no-key
    send_key: bool = True
    expected_backend: str = ""    # backend targets: the backend the call should reach
    note: str = ""


@dataclass
class Result:
    step: Step
    icon: str
    status: int | str
    latency_ms: int = 0
    answer: str = ""
    served_by: str = ""
    detail: str = ""
    call: object = field(default=None, repr=False)


def request_shapes(model, kind, btype, apis, gateway_url, prompt):
    """[(api, surface, url, body, parser)] for every API surface in `apis` ({name: path}) that can call `model`."""
    q = urllib.parse.quote(model, safe="")
    msgs = [{"role": "user", "content": prompt}]
    uni, aoai, unified = apis.get("universal-llm-api"), apis.get("azure-openai-api"), apis.get("unified-ai-api")
    g = gateway_url.rstrip("/")
    out = []

    def aoai_style(path, op, body):
        return f"{g}/{path}/deployments/{q}/{op}?api-version={AOAI_API_VERSION}", body

    if kind == "chat" and btype in OPENAI_COMPAT:
        if uni is not None:
            if uni.endswith("openai") and btype in AOAI_TYPES:  # a universal API published on an /openai path
                out.append(("universal-llm-api", "deployments/{model}/chat/completions", *aoai_style(uni, "chat/completions", {"messages": msgs}), "openai-chat"))
            elif not uni.endswith("openai"):
                out.append(("universal-llm-api", "chat/completions", f"{g}/{uni}/chat/completions", {"model": model, "messages": msgs}, "openai-chat"))
        if aoai is not None and btype in AOAI_TYPES:
            out.append(("azure-openai-api", "deployments/{model}/chat/completions", *aoai_style(aoai, "chat/completions", {"messages": msgs}), "openai-chat"))
        if unified is not None:
            out.append(("unified-ai-api", "v1/chat/completions", f"{g}/{unified}/v1/chat/completions", {"model": model, "messages": msgs}, "openai-chat"))
    elif kind == "chat" and unified is not None and btype == "aws-bedrock":
        out.append(("unified-ai-api", "bedrock/model/{model}/converse", f"{g}/{unified}/bedrock/model/{q}/converse",
                    {"messages": [{"role": "user", "content": [{"text": prompt}]}]}, "bedrock"))
    elif kind == "chat" and unified is not None and btype == "gemini":
        out.append(("unified-ai-api", "gemini/v1beta/models/{model}:generateContent", f"{g}/{unified}/gemini/v1beta/models/{q}:generateContent",
                    {"contents": [{"role": "user", "parts": [{"text": prompt}]}]}, "gemini"))
    elif kind == "chat" and unified is not None and btype == "anthropic":
        out.append(("unified-ai-api", "claude/v1/messages", f"{g}/{unified}/claude/v1/messages",
                    {"model": model, "max_tokens": 256, "messages": msgs}, "claude"))
    elif kind == "embeddings" and btype in EMBEDDING_TYPES:
        body = {"model": model, "input": prompt}
        if uni is not None and not uni.endswith("openai"):
            out.append(("universal-llm-api", "embeddings", f"{g}/{uni}/embeddings", body, "embeddings"))
        if aoai is not None and btype in AOAI_TYPES:
            out.append(("azure-openai-api", "deployments/{model}/embeddings", *aoai_style(aoai, "embeddings", {"input": prompt}), "embeddings"))
        if unified is not None:
            out.append(("unified-ai-api", "v1/embeddings", f"{g}/{unified}/v1/embeddings", body, "embeddings"))
    elif kind == "image" and btype in IMAGE_TYPES and unified is not None:
        out.append(("unified-ai-api", "v1/images/generations", f"{g}/{unified}/v1/images/generations",
                    {"model": model, "prompt": prompt, "n": 1, "size": "1024x1024"}, "image"))
    return out


def missing_surface(kind, btype):
    """Why request_shapes found nothing (for the report)."""
    if kind == "unsupported":
        return "realtime / audio / video model: not callable with a simple request"
    if kind == "chat" and btype in ("aws-bedrock", "gemini", "anthropic"):
        return f"{btype} is native only: needs unified-ai-api (llm-backend-onboarding features.unified_ai_api) in the product"
    if kind == "image":
        return "images need unified-ai-api (/v1/images) in the product"
    if kind == "embeddings" and btype not in EMBEDDING_TYPES:
        return f"the gateway routes no embeddings to {btype} backends"
    return "no LLM API of the product can call this model"


def answer(parser, body):
    """Short readable result of a successful response ("" when the shape is unexpected)."""
    try:
        if parser == "openai-chat":
            return body["choices"][0]["message"]["content"] or "(empty content)"
        if parser == "embeddings":
            return f"{len(body['data'][0]['embedding'])}-dimension vector"
        if parser == "bedrock":
            return body["output"]["message"]["content"][0]["text"]
        if parser == "gemini":
            return body["candidates"][0]["content"]["parts"][0]["text"]
        if parser == "claude":
            return body["content"][0]["text"]
        if parser == "image":
            d = body["data"][0]
            return "image URL" if d.get("url") else f"image ({len(d.get('b64_json', '')) * 3 // 4 // 1024} KB, base64)"
        if parser == "mcp":
            return f"server {body['result']['serverInfo']['name']}"
    except (TypeError, KeyError, IndexError):
        pass
    return ""


class Explorer:
    """Discovery and calls for one environment (environments/<env>)."""

    def __init__(self, env, prompt=DEFAULT_PROMPT, key_source="auto", backend_key="auto"):
        self.gw = A.Gateway(env)
        self.env, self.prompt = env, prompt
        self.key_source, self.backend_key = key_source, backend_key
        self.contract = self._backend_contract()
        self.backends = {b["backendId"]: b for b in self.contract.get("backends", [])}
        self.aliases = {a["name"]: a for a in self.contract.get("modelAliases", [])}
        self.models = {}
        for b in self.backends.values():
            for m in b.get("supportedModels", []):
                e = self.models.setdefault(m["name"], {"types": set(), "backends": []})
                e["types"].add(b["backendType"])
                e["backends"].append(b["backendId"])
        for e_name, e in self.models.items():
            e["kind"] = model_kind(e_name, e["types"])
        self.apis = {a["name"]: a for a in self.gw.get(f"{self.gw.svc}/apis", api=A.APIM_MCP_API)["value"]}
        try:
            self.contract_files = A.load_contracts(env)
            self.contract_note = ""
        except ImportError:
            self.contract_files = []
            self.contract_note = "python-hcl2 isn't installed: contracts are found by product name only"
        self.product_contract = {s["product_id"]: (c, s) for c in self.contract_files for s in c["services"]}
        self._keys, self._debug = {}, {}

    # -- discovery ----------------------------------------------------------------------------------
    def _backend_contract(self):
        xml = self.gw.fragment("backend-contract")
        m = re.search(r"<set-body>(.*)</set-body>", xml or "", re.S)
        if not m:
            raise LookupError("no backend-contract fragment on the gateway: apply stacks/llm-backend-onboarding first")
        return json.loads(html.unescape(m.group(1).strip()))

    def product_apis(self, product_id):
        """{api name: {"path", "type"}} of the APIs the product grants (MCP APIs included)."""
        return self.gw.cached(("explorer-apis", product_id), lambda: {
            a["name"]: {"path": a["properties"].get("path", ""), "type": a["properties"].get("type", "http")}
            for a in self.gw.get(f"{self.gw.svc}/products/{product_id}/apis", api=A.APIM_MCP_API)["value"]})

    def alias_info(self, name):
        """(kind, backend types) of an alias, from its members."""
        members = [m for m in self.aliases[name].get("models", []) if m in self.models]
        types = set().union(*(self.models[m]["types"] for m in members)) if members else set()
        return (self.models[members[0]]["kind"] if members else "chat"), types

    def catalogue(self):
        """Rows for the contracts (products), backends, models and aliases tables."""
        contracts = []
        for p in sorted(self.gw.products(), key=lambda p: p["name"]):
            pid = p["name"]
            sub = self.gw.subscription(pid)
            s = self.gw.settings(pid)
            c = self.product_contract.get(pid)
            contracts.append({
                "contract file": c[0]["file"].removesuffix(".tfvars") if c else "",
                "product": pid,
                "APIs": ", ".join(self.product_apis(pid)),
                "models": ", ".join(s["allowed_models"]) or "all",
                "JWT": ("yes" + (f" ({', '.join(s['required_roles'])})" if s["required_roles"] else "")) if s["jwt_required"] else "",
                "subscription": "active" if sub else "none",
            })
        backends = [{
            "backend": b["backendId"], "type": b["backendType"], "auth": b.get("authType", ""),
            "endpoint": urllib.parse.urlparse(b.get("endpoint", "")).netloc or b.get("endpoint", ""),
            "models": ", ".join(m["name"] for m in b.get("supportedModels", [])),
        } for b in self.backends.values()]
        models = [{
            "model": n, "kind": e["kind"], "backend types": ", ".join(sorted(e["types"])),
            "backends": ", ".join(e["backends"]),
            "in aliases": ", ".join(a for a, d in self.aliases.items() if n in d.get("models", [])),
        } for n, e in sorted(self.models.items())]
        aliases = [{"alias": n, "strategy": a.get("strategy", ""), "members": ", ".join(a.get("models", []))}
                   for n, a in sorted(self.aliases.items())]
        mcp = [{"MCP server": n, "path": a["properties"].get("path", ""),
                "kind": "passthrough" if a["properties"].get("backendId") else "from API operations"}
               for n, a in sorted(self.apis.items()) if a["properties"].get("type") == "mcp"]
        return {"contracts": contracts, "backends": backends, "models": models, "aliases": aliases, "mcp servers": mcp}

    def resolve(self, target):
        """(kind, value): ("contract", contract dict) | ("product", id) | ("backend", id) | ("alias", name) |
        ("model", name) | ("mcp", API name). Exact names first (case-insensitive), then a unique partial match."""
        t = (target or "").strip()
        if not t:
            raise ValueError("TARGET is empty: pick a name from the catalogue")
        low = t.lower()
        candidates = (
            [("contract", c, [c["file"].removesuffix(".tfvars"), c["file"], c["postfix"]]) for c in self.contract_files]
            + [("product", p["name"], [p["name"], p["properties"].get("displayName", "")]) for p in self.gw.products()]
            + [("backend", b, [b]) for b in self.backends]
            + [("alias", a, [a]) for a in self.aliases]
            + [("model", m, [m]) for m in self.models]
            + [("mcp", n, [n, a["properties"].get("displayName", "")]) for n, a in self.apis.items()
               if a["properties"].get("type") == "mcp"]
        )
        exact = [(k, v) for k, v, names in candidates if low in (n.lower() for n in names)]
        if exact:
            return exact[0]
        n = norm(t)
        partial = [(k, v, names[0]) for k, v, names in candidates if n and any(n in norm(x) for x in names)]
        # A contract and its own products are the same target: keep the contract.
        owned = {s["product_id"] for k, v, _ in partial if k == "contract" for s in v["services"]}
        partial = [p for p in partial if not (p[0] == "product" and p[1] in owned)]
        if len(partial) == 1:
            return partial[0][:2]
        if partial:
            raise ValueError(f"'{t}' matches several names, be more specific: " + ", ".join(f"{p[2]} ({p[0]})" for p in partial))
        raise ValueError(f"'{t}' is not a contract, product, backend, alias, model or MCP server of {self.env}: see the catalogue")

    # -- planning -----------------------------------------------------------------------------------
    def plan(self, target, include=("chat", "embeddings", "image"), guardrails=True):
        """(description, [Step]) for a target name."""
        kind, value = self.resolve(target)
        if kind == "contract":
            steps = []
            for s in value["services"]:
                steps += self._product_steps(s["product_id"], include, guardrails)
            return f"access contract {value['file']} ({len(value['services'])} service(s))", steps
        if kind == "product":
            return f"product {value}", self._product_steps(value, include, guardrails)
        if kind == "backend":
            b = self.backends[value]
            steps = []
            for m in b.get("supportedModels", []):
                mk = self.models[m["name"]]["kind"]
                if mk in include or mk == "unsupported":
                    steps += self._direct_steps(m["name"], mk, {b["backendType"]}, expected_backend=value)
            return f"backend {value} ({b['backendType']}, {len(b.get('supportedModels', []))} model(s))", steps
        if kind == "mcp":
            return f"MCP server {value}", [self._mcp_direct(value)]
        if kind == "alias":
            ak, types = self.alias_info(value)
            return f"alias {value} → {', '.join(self.aliases[value].get('models', []))}", self._direct_steps(value, ak, types)
        e = self.models[value]
        return f"model {value} ({e['kind']}, served by {', '.join(e['backends'])})", self._direct_steps(value, e["kind"], e["types"])

    def _steps_for(self, name, kind, types, apis, product, expected_backend=""):
        steps = []
        for btype in sorted(types) or [""]:
            for api, surface, url, body, parser in request_shapes(name, kind, btype, apis, self.gw.gateway_url, self.prompt):
                steps.append(Step(name, kind, btype, api, surface, url=url, body=body, parser=parser, product=product,
                                  expected_backend=expected_backend))
        unique = {(s.api, s.surface): s for s in steps}  # an alias over two compatible types: one call per surface
        if unique:
            return list(unique.values())
        btype = ", ".join(sorted(types))
        return [Step(name, kind, btype, product=product, note=missing_surface(kind, sorted(types)[0] if types else ""))]

    def _product_steps(self, pid, include, guardrails):
        apis = self.product_apis(pid)
        llm = {n: a["path"] for n, a in apis.items() if n in LLM_APIS}
        settings = self.gw.settings(pid)
        if not self.gw.subscription(pid):
            return [Step("", "", product=pid, note="the product has no active subscription")]
        names = settings["allowed_models"] or (sorted(self.models) + sorted(self.aliases))
        steps = []
        for name in names:
            if name in self.aliases:
                k, types = self.alias_info(name)
            elif name in self.models:
                k, types = self.models[name]["kind"], self.models[name]["types"]
            else:
                steps.append(Step(name, "?", product=pid, note="allowed by the contract, but no backend serves it"))
                continue
            if k in include or k == "unsupported":
                steps += self._steps_for(name, k, types, llm, pid) if llm else []
        for n, a in apis.items():
            if a["type"] == "mcp":
                steps.append(self._mcp_step(n, pid))
            elif n not in LLM_APIS and n != "release-version-api":
                steps.append(Step("", a["type"], api=n, product=pid, note="not an LLM or MCP API: not covered by this notebook"))
        callable_steps = [s for s in steps if s.url and s.kind == "chat"]
        if guardrails and callable_steps:
            first = callable_steps[0]
            steps.append(Step(first.model, first.kind, first.backend_type, first.api, first.surface, url=first.url, body=first.body,
                              parser=first.parser, product=pid, expect=(401,), check="no-key", send_key=False,
                              note="no subscription key: the gateway must reject the call"))
            if settings["allowed_models"]:
                denied = next((m for m, e in sorted(self.models.items()) if e["kind"] == "chat" and m not in settings["allowed_models"]), None)
                if denied:
                    s = self._steps_for(denied, "chat", self.models[denied]["types"], llm, pid)
                    if s and s[0].url:
                        d = s[0]
                        d.expect, d.check, d.note = (403,), "denied-model", "not in allowed_models: validate-model-access must answer 403"
                        steps.append(d)
        return steps

    def _mcp_step(self, api_name, pid):
        a = self.apis.get(api_name, {})
        props = a.get("properties", {})
        path = props.get("path", api_name).strip("/")
        url = f"{self.gw.gateway_url}/{path}" if props.get("backendId") else f"{self.gw.gateway_url}/{path}/mcp"
        body = {"jsonrpc": "2.0", "id": 1, "method": "initialize",
                "params": {"protocolVersion": "2025-03-26", "capabilities": {}, "clientInfo": {"name": "citadel-explorer", "version": "1.0"}}}
        return Step("", "mcp", api=api_name, surface="MCP initialize", url=url, body=body, parser="mcp", product=pid)

    def _mcp_direct(self, api_name):
        """MCP initialize with the all-access subscription, else a product that grants the server."""
        if any(s["name"] == ALL_ACCESS and s["properties"].get("state") == "active" for s in self.gw.subscriptions()):
            return self._mcp_step(api_name, ALL_ACCESS)
        pid = next((p["name"] for p in self.gw.products() if self.gw.subscription(p["name"]) and api_name in self.product_apis(p["name"])), None)
        if not pid:
            return Step("", "mcp", api=api_name, note="no active subscription can call it")
        return self._mcp_step(api_name, pid)

    def _direct_steps(self, name, kind, types, expected_backend=""):
        """Steps for a backend / model / alias: the all-access subscription, else a product that grants the model."""
        if kind == "unsupported":
            return [Step(name, kind, ", ".join(sorted(types)), note=missing_surface(kind, ""))]
        product, apis = self._key_scope(name, kind, types)
        if product is None:
            return [Step(name, kind, ", ".join(sorted(types)),
                         note="no active subscription can call it: enable the all-access subscription or set BACKEND_KEY to a product")]
        return self._steps_for(name, kind, types, apis, product, expected_backend)

    def _key_scope(self, name, kind, types):
        """(product id or ALL_ACCESS, {api: path}) used to call a model directly."""
        all_llm = {n: a["properties"].get("path", "") for n, a in self.apis.items() if n in LLM_APIS}
        if self.backend_key not in ("auto", ALL_ACCESS):
            pid = self.backend_key
            return pid, {n: a["path"] for n, a in self.product_apis(pid).items() if n in LLM_APIS}
        master = next((s for s in self.gw.subscriptions() if s["name"] == ALL_ACCESS and s["properties"].get("state") == "active"), None)
        # The unified AI API answers 401 product_required to a subscription without a product.
        master_apis = {n: p for n, p in all_llm.items() if n != "unified-ai-api"}
        if master and any(request_shapes(name, kind, t, master_apis, self.gw.gateway_url, "x") for t in types):
            return ALL_ACCESS, master_apis
        candidates = []
        for p in self.gw.products():
            pid = p["name"]
            s = self.gw.settings(pid)
            if not self.gw.subscription(pid) or (s["allowed_models"] and name not in s["allowed_models"]):
                continue
            apis = {n: a["path"] for n, a in self.product_apis(pid).items() if n in LLM_APIS}
            if any(request_shapes(name, kind, t, apis, self.gw.gateway_url, "x") for t in types):
                candidates.append((s["jwt_required"], pid, apis))
        if not candidates:
            return None, {}
        _, pid, apis = sorted(candidates)[0]  # prefer a product without JWT
        return pid, apis

    # -- calls --------------------------------------------------------------------------------------
    def key(self, product):
        """(key, source) for a product or ALL_ACCESS; the key stays in memory."""
        if product in self._keys:
            return self._keys[product]
        if product == ALL_ACCESS:
            k = self.gw.post(f"{self.gw.svc}/subscriptions/{ALL_ACCESS}/listSecrets")["primaryKey"]
            self._keys[product] = (k, "APIM all-access subscription")
            return self._keys[product]
        c = self.product_contract.get(product)
        if self.key_source in ("auto", "key-vault") and c and c[0]["key_vault"]["enabled"]:
            vault = (c[0]["key_vault"]["id"] or "").rstrip("/").split("/")[-1] or self.gw.key_vault
            try:
                k = self.gw.secret(vault, c[1]["key_secret"])
                if k:
                    self._keys[product] = (k, f"Key Vault {vault}/{c[1]['key_secret']}")
                    return self._keys[product]
            except A.AzError as e:
                if self.key_source == "key-vault":
                    raise
                print(f"{INFO} {product}: Key Vault not readable ({str(e)[:120]}), using the APIM subscription key")
        k = self.gw.keys(product)["primaryKey"]
        self._keys[product] = (k, "APIM subscription (listSecrets)")
        return self._keys[product]

    def headers(self, step):
        """(headers, skip reason, required roles the test client's token lacks)."""
        h = {"Content-Type": "application/json"}
        if step.kind == "mcp":
            h["Accept"] = "application/json, text/event-stream"
        if not step.send_key:
            return h, "", []
        h["api-key"] = self.key(step.product)[0]
        if step.product != ALL_ACCESS:
            s = self.gw.settings(step.product)
            if s["jwt_required"]:
                try:
                    token = self.gw.token(s["audience"] or None)
                except Exception as e:  # noqa: BLE001 - any token failure is reported, not raised
                    return h, f"JWT required, no token for the test client ({str(e)[:100]}): set JWT_TEST_CLIENT_ID / _SECRET", []
                h["Authorization"] = "Bearer " + token
                roles = set(A.jt.token_claims(token).get("roles") or [])
                if s["required_roles"] and not roles & set(s["required_roles"]):
                    return h, "", s["required_roles"]
        return h, "", []

    def _debug_token(self, api):
        if api not in self._debug:
            creds = self.gw.az.rest("POST", self.gw.url(f"{self.gw.svc}/gateways/managed/listDebugCredentials", A.APIM_DEBUG_API),
                                    body={"credentialsExpireAfter": "PT1H", "apiId": f"{self.gw.apim_id}/apis/{api}",
                                          "purposes": ["tracing"]}, check=False)
            self._debug[api] = (creds or {}).get("token")
        return self._debug[api]

    def served_by(self, call):
        """Backend ID (or host) the gateway forwarded to, from the APIM debug trace of the call."""
        trace_id = call.headers.get("Apim-Trace-Id")
        if not trace_id:
            return ""
        trace = self.gw.az.rest("POST", self.gw.url(f"{self.gw.svc}/gateways/managed/listTrace", A.APIM_DEBUG_API),
                                body={"traceId": trace_id}, check=False) or {}
        text = json.dumps((trace.get("traceEntries") or {}).get("backend") or [])
        hosts = re.findall(r"https://([^/\"\\\s]+)", text)
        by_host = {}
        for b in self.backends.values():
            by_host.setdefault(urllib.parse.urlparse(b.get("endpoint", "")).netloc.lower(), []).append(b["backendId"])
        for h in reversed(hosts):
            if h.lower() in by_host:
                return ", ".join(by_host[h.lower()])
        return hosts[-1] if hosts else ""

    def run(self, steps, trace=False, timeout=120):
        """Executes the steps; trace=True asks APIM which backend served each call (debug trace)."""
        results = []
        for s in steps:
            if not s.url:
                results.append(Result(s, SKIP if s.note else INFO, "-", detail=s.note))
                continue
            h, skip, missing_roles = self.headers(s)
            if skip:
                results.append(Result(s, SKIP, "-", detail=skip))
                continue
            if missing_roles and s.check == "call":
                s = replace(s, expect=(403,), check="missing-role",
                            note=f"the test client has none of the roles {', '.join(missing_roles)}: 403 expected "
                                 "(grant one to the test client to test the allowed path)")
            if trace and s.send_key and s.api:
                tok = self._debug_token(s.api)
                if tok:
                    h["Apim-Debug-Authorization"] = tok
            call = A.http(s.method, s.url, h, s.body, timeout)
            if call.status == 429 and s.check == "call":
                time.sleep(min(int(call.headers.get("Retry-After", "5") or 5), 20))
                call = A.http(s.method, s.url, h, s.body, timeout)
            body = call.body
            if s.kind == "mcp" and body is None and call.text.startswith(("event:", "data:")):
                data = next((ln[5:].strip() for ln in call.text.splitlines() if ln.startswith("data:")), "")
                try:
                    body = json.loads(data)
                except ValueError:
                    body = None
            ok = call.status in s.expect
            text = answer(s.parser, body) if ok and s.check == "call" else ""
            detail = s.note if s.check != "call" else ""
            if not ok:
                page = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", call.text)) if call.text.lstrip().startswith("<") else call.text
                detail = (": ".join(x for x in (call.code, call.message) if x) or call.error or page[:160]).strip()
            elif s.check == "call" and not text:
                ok, detail = False, f"unexpected response shape: {call.text[:120]}"
            served = self.served_by(call) if trace and ok and s.check == "call" else call.headers.get("UAIG-Backend", "")
            served = "" if served == "not-set" else served
            if ok and s.expected_backend and served and s.expected_backend not in served:
                detail = f"served by {served}, not {s.expected_backend} (the model is in a pool with other backends)"
            results.append(Result(s, OK if ok else FAIL, call.status, call.latency_ms, text, served, detail, call))
        return results


def rows(results, width=70):
    """Table rows of results for acceptance.print_table."""
    out = []
    for r in results:
        s = r.step
        what = s.check if s.check != "call" else (s.surface or "")
        out.append({
            "": r.icon, "product": s.product, "API": s.api.replace("-api", ""), "call": what, "model": s.model,
            "kind": s.kind, "backend type": s.backend_type, "HTTP": r.status,
            "ms": r.latency_ms or "", "served by": r.served_by,
            "result": (r.answer or r.detail).replace("\n", " ")[:width],
        })
    return out


def summary(results):
    counts = {}
    for r in results:
        counts[r.icon] = counts.get(r.icon, 0) + 1
    return "  ".join(f"{icon} {n}" for icon, n in counts.items())
